"""One working surface for the existing specialist Analysis tools."""
from __future__ import annotations

import streamlit as st

from rank42.ui_pages.common import PAGE_ICONS, embedded_page_title, title
from . import (
    descent_page, geometry_search_page, independence_page, lattices_page, pencils_page,
    point_hunt_page, points_page, quartics_page, saturation_page,
)


def _family_geometry(db, ctx):
    geometry_search_page.render(db, ctx, embedded=True)


_TOOLS = {
    "Descent": (
        descent_page.page, PAGE_ICONS["Descent"],
        "Compute rigorous rank bounds and inspect rank evidence.",
    ),
    "Independence": (
        independence_page.page, PAGE_ICONS["Independence"],
        "Certify whether exact points add new independent directions.",
    ),
    "Saturation": (
        saturation_page.page, PAGE_ICONS["Saturation"],
        "Test and improve the subgroup generated by known points.",
    ),
    "Points": (
        points_page.page, PAGE_ICONS["Points"],
        "Review exact rational points and their proof status.",
    ),
    "Point Hunt": (
        point_hunt_page.render, ":material/travel_explore:",
        "Search one curve for new exact points, then inspect coverage and certificates.",
    ),
    "Quartics": (
        quartics_page.page, PAGE_ICONS["Quartics"],
        "Search quartic models and coverings for new rational points.",
    ),
    "Lattices": (
        lattices_page.page, PAGE_ICONS["Lattices"],
        "Study generator heights, basis quality, and lattice holes.",
    ),
    "Pencils": (
        pencils_page.page, PAGE_ICONS["Pencils"],
        "Compare elliptic pencils and their best specializations.",
    ),
    "Family Geometry": (
        _family_geometry, ":material/account_tree:",
        "Run geometry-first family or torsion searches with exact follow-up.",
    ),
}

_GROUPS = (
    ("Rank proof", ("Descent", "Independence", "Saturation")),
    ("Find points", ("Points", "Point Hunt", "Quartics")),
    ("Geometry", ("Lattices", "Pencils", "Family Geometry")),
)

_HANDOFF_ALIASES = {
    "MW Geometry": "Lattices",
    "Lattices & Heights": "Lattices",
    "Rank Proof": "Descent",
}


def _tool_picker():
    selected = str(st.session_state.get("tools_selection") or "Descent")
    if selected not in _TOOLS:
        selected = "Descent"
        st.session_state["tools_selection"] = selected
    with st.container(key="rh-tools-picker", border=True):
        columns = st.columns([1, 1, 1.15], gap="xsmall")
        for column, (group_name, names) in zip(columns, _GROUPS):
            with column:
                group_key = f"rh-tools-group-{group_name.lower().replace(' ', '-')}"
                with st.container(key=group_key):
                    st.markdown(f"**{group_name}**")
                    with st.container(horizontal=True, wrap=False, gap="xsmall"):
                        for name in names:
                            _, icon, description = _TOOLS[name]
                            if st.button(
                                name, icon=icon, help=description,
                                key=f"tools-select-{name.lower()}",
                                type="primary" if selected == name else "secondary",
                                width="content",
                            ):
                                st.session_state["tools_selection"] = name
                                st.rerun()
    return selected


def page(db, ctx):
    title("Tools", icon=PAGE_ICONS["Tools"])
    selected = _tool_picker()
    handler, _, description = _TOOLS[selected]
    st.markdown(f"### {selected}")
    st.caption(description)
    try:
        with embedded_page_title():
            handler(db, ctx)
    finally:
        # Keep tool-to-tool handoffs inside the toolbox. Other destinations,
        # such as Curves and Jobs, continue to use their existing routes.
        destination = str(st.session_state.get("rh_page") or "Tools")
        destination = _HANDOFF_ALIASES.get(destination, destination)
        if destination in _TOOLS:
            st.session_state["tools_selection"] = destination
            st.session_state["rh_page"] = "Tools"
