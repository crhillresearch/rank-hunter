_HANDOFF_ALIASES = {
    "MW Geometry": "Lattices",
    "Lattices & Heights": "Lattices",
    "Rank Proof": "Descent",
}


def _tool_picker():
    selected = str(
        st.session_state.get("tools_selection")
        or st.query_params.get("rh_tool")
        or "Descent"
    )
    if selected not in _TOOLS:
        selected = "Descent"
    st.session_state["tools_selection"] = selected
    grouped = [
        {
            "label": group_name,
            "tools": [
                {
                    "name": name,
                    "icon": _TOOLS[name][1].removeprefix(":material/").removesuffix(":"),
                    "description": _TOOLS[name][2],
                }
                for name in names
            ],
        }
        for group_name, names in _GROUPS
    ]
    config = json.dumps({
        "selected": selected,
        "groups": grouped,
        "pageTitle": "Tools",
        "pageIcon": "handyman",
    }).replace("<", "\\u003c")
    st.html(
        '<div id="rh-tools-commandbar" class="rh-tools-commandbar-host" '
        f'aria-label="Research tools; current tool {html.escape(selected)}"></div>',
    )
    _TOOLS_COMMAND_BAR(data=json.loads(config), key="rh-tools-command-runtime")
    with st.container(key="rh-tools-command-bridge"):
        for name in _TOOLS:
            slug = name.lower().replace(" ", "-")
            if st.button(name, key=f"tools-select-{slug}"):
                st.session_state["tools_selection"] = name
                st.rerun()
    return selected


def page(db, ctx):
    selected = _tool_picker()
    handler, _, description = _TOOLS[selected]
    st.markdown(f"### {selected}")
    st.caption(description)
    try:
        with embedded_page_title():
            handler(db, ctx)
    finally:
        # Keep tool-to-tool handoffs inside the toolbox. Other destinations,
        # such as Curves and Jobs, continue to use their existing routes.
        destination = str(st.session_state.get("rh_page") or "Tools")
        destination = _HANDOFF_ALIASES.get(destination, destination)
        if destination in _TOOLS:
            st.session_state["tools_selection"] = destination
            st.session_state["rh_page"] = "Tools"
